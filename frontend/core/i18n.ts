export type TranslationKey = keyof typeof english

let currentLocale: AppLocale = 'pt-BR'

export const normalizeLocale = (value?: string | null): AppLocale =>
  `${value || ''}`.toLowerCase().startsWith('en') ? 'en' : 'pt-BR'

export const setLocale = (locale: AppLocale): void => {
  currentLocale = locale
}

export const getLocale = (): AppLocale => currentLocale

export const t = (
  key: TranslationKey,
  variables: Record<string, string | number> = {},
): string => {
  const source: string = currentLocale === 'en' ? english[key] : key
  return Object.entries(variables).reduce(
    (result, [name, value]) => result.split(`{${name}}`).join(`${value}`),
    source,
  )
}

export const formatNumber = (value: number): string =>
  value.toLocaleString(currentLocale)
